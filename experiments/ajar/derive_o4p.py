"""O4' (residuals_rules.md revision 5): config_o4p/ from config_rule/, by effect type.

    python derive_o4p.py      -> config_o4p/<suite>.yaml, config_o4p/SINKS.md, live/grant_args_O4p.json

Class of a sink (by its name and effect):
  high    moves money, changes credentials (access_control_sinks), sends outside the
          workspace (e-mail, calendar invitations to participants, a web post), deletes,
          shares outward (file share, inviting a user into the workspace)
  medium  any other state change inside the workspace
  low     a network read with no user data (a get_* sink taking a url)
Leading args: target / addressee / magnitude only (see LEADING).
Checks: high request-only + grants on the leading args; medium any-trusted on the
leading args, no grants; low no origin check (sink_origins none), no grants.
"""
from __future__ import annotations

import json
import os
import re

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "config_rule")
OUT = os.path.join(HERE, "config_o4p")
R0 = json.load(open(os.path.join(HERE, "live", "grant_args_R0.json")))

MONEY = re.compile(r"(money|transaction|pay|reserve)")
DELETE = re.compile(r"^(delete|cancel|remove)_")
SHARE = re.compile(r"(share|invite)")
OUTSIDE = re.compile(r"(^send_email$|^post_|participants)")
# leading args (target / addressee / magnitude), by name
ADDRESSEE = {"recipient", "recipients", "cc", "bcc", "email", "user_email", "participants", "channel", "user"}
MAGNITUDE = {"amount"}
CREDENTIAL = {"password"}
PAYEE = {"hotel", "restaurant", "company"}
OBJECT_ID = re.compile(r"(^|_)id$")


def classify(tool: str, args: list[str], access_control: set[str]) -> tuple[str, str]:
    if tool in access_control:
        return "high", "changes credentials"
    if MONEY.search(tool):
        return "high", "moves money"
    if DELETE.search(tool):
        return "high", "deletes"
    if SHARE.search(tool):
        return "high", "shares outward"
    if OUTSIDE.search(tool) or ("participants" in args and tool.startswith("create_")):
        return "high", "sends outside the workspace"
    if tool.startswith("get_") and "url" in args:
        return "low", "network read, no user data"
    return "medium", "changes state inside the workspace"


def leading(tool: str, cls: str, args: list[str]) -> list[str]:
    if cls == "low":
        return []
    out = []
    for a in args:
        if a in ADDRESSEE or a in MAGNITUDE or a in CREDENTIAL or a in PAYEE:
            out.append(a)
        elif a == "url" and tool.startswith("post_"):
            out.append(a)          # the URL posted to
        elif OBJECT_ID.search(a) and (DELETE.search(tool) or SHARE.search(tool)
                                       or "participants" in tool or MONEY.search(tool)):
            out.append(a)          # the id of the object deleted / shared / redirected
    return out


def main():
    os.makedirs(OUT, exist_ok=True)
    from agentdojo.task_suite.load_suites import get_suites
    from check_wrapper import VERSIONS
    rows, grant_args = [], {}
    for suite in ("banking", "slack", "travel", "workspace"):
        cfg = yaml.safe_load(open(os.path.join(SRC, f"{suite}.yaml")))
        tools = {t.name: list(t.parameters.model_json_schema().get("properties", {}))
                 for t in get_suites("v1")[suite].tools}
        sinks = sorted(set(cfg.get("egress_sinks") or []) | set(cfg.get("integrity_sinks") or []))
        ac = set(cfg.get("access_control_sinks") or [])
        driving, origins, ga = {}, {}, {}
        for t in sinks:
            cls, why = classify(t, tools.get(t, []), ac)
            lead = leading(t, cls, tools.get(t, []))
            old = cfg.get("driving_args", {}).get(t, [])
            if lead:
                driving[t] = lead
            origins[t] = {"high": "request-only", "medium": "any-trusted", "low": "none"}[cls]
            if cls == "high" and lead:
                kinds = R0.get(suite, {}).get(t, {})
                ga[t] = {a: kinds[a] for a in lead if a in kinds}
                if not ga[t]:
                    del ga[t]
            rows.append((suite, t, cls, why, lead, sorted(set(old) - set(lead)), ga.get(t)))
        cfg["driving_args"] = driving
        cfg["sink_origins"] = origins
        grant_args[suite] = ga
        with open(os.path.join(OUT, f"{suite}.yaml"), "w") as f:
            f.write(f"# Generated by derive_o4p.py from config_rule/{suite}.yaml — O4' (revision 5):\n"
                    f"# leading args by effect class; sink_origins per class. Do not edit by hand.\n")
            yaml.safe_dump(cfg, f, sort_keys=True)
    json.dump(grant_args, open(os.path.join(HERE, "live", "grant_args_O4p.json"), "w"), indent=1, sort_keys=True)
    with open(os.path.join(OUT, "SINKS.md"), "w") as f:
        f.write("# O4′ sinks — class, leading args, checks (generated by derive_o4p.py; for review)\n\n"
                "high: request-only + grants on the leading args · medium: any-trusted on the leading "
                "args, no grant · low: no origin check, no grant. floor all_mutating and "
                "access_control unchanged.\n\n"
                "| suite | sink | class | why | leading args | grant args (kind) | demoted (driving in config_rule, not leading now) |\n"
                "|---|---|---|---|---|---|---|\n")
        for s, t, c, w, lead, dem, ga in rows:
            f.write(f"| {s} | `{t}` | **{c}** | {w} | {', '.join(lead) or '—'} | "
                    f"{', '.join(f'{a} ({k})' for a, k in (ga or {}).items()) or '—'} | {', '.join(dem) or '—'} |\n")
    for r in rows:
        print(r[0], r[1], r[2], r[4], "demoted:", r[5])


if __name__ == "__main__":
    main()
